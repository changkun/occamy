// sum adds up the rows that match.
func (rep *report) sum(rows []row, size int, codec string, scene func(string) bool, class func(string) bool) row {
	s := row{Size: size, Codec: codec}
	for _, r := range rows {
		if r.Size != size || r.Codec != codec || !scene(r.Scene) || !class(r.Class) {
			continue
		}
		s.Tiles += r.Tiles
		s.Pixels += r.Pixels
		s.Bytes += r.Bytes
		s.EncodeNs += r.EncodeNs
		s.DecodeNs += r.DecodeNs
		s.SSIMSum += r.SSIMSum
		s.Mismatch += r.Mismatch
	}
	return s
}

func every(string) bool             { return true }
func is(v string) func(string) bool { return func(s string) bool { return s == v } }
func lowColour(c string) bool       { return c != ">256" }
func highColour(c string) bool      { return c == ">256" }

func (r row) bpp() float64   { return 8 * float64(r.Bytes) / float64(max(1, r.Pixels)) }
func (r row) ssim() float64  { return r.SSIMSum / float64(max(1, r.Tiles)) }
func (r row) encUs() float64 { return r.EncodeNs / 1e3 / float64(max(1, r.Tiles)) }
func (r row) decUs() float64 { return r.DecodeNs / 1e3 / float64(max(1, r.Tiles)) }

func (rep *report) scenes() []string {
	var s []string
	for k := range rep.Frames {
		s = append(s, k)
	}
	order := []string{"desktop", "terminal", "terminal-aa", "browser", "photo", "drag", "scroll", "motion"}
	slices.SortFunc(s, func(a, b string) int {
		ia, ib := slices.Index(order, a), slices.Index(order, b)
		if ia < 0 {
			ia = len(order)
		}
		if ib < 0 {
			ib = len(order)
		}
		if ia != ib {
			return ia - ib
		}
		return strings.Compare(a, b)
	})
	return s
}

func (rep *report) lossless() []string {
	var s []string
	for _, c := range rep.Codecs {
		if !strings.Contains(c, " q") {
			s = append(s, c)
		}
	}
	return s
}

// families are the lossy curves, in order.
func (rep *report) families() []string {
	var s []string
	for _, c := range rep.Codecs {
		if f, _, ok := strings.Cut(c, " q"); ok && !slices.Contains(s, f) {
			s = append(s, f)
		}
	}
	return s
}

func table(b *strings.Builder, head []string, rows [][]string) {
	b.WriteString("| " + strings.Join(head, " | ") + " |\n|")
	for range head {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	b.WriteString("\n")
}

func f1(v float64) string { return fmt.Sprintf("%.1f", v) }
func f2(v float64) string { return fmt.Sprintf("%.2f", v) }
func f3(v float64) string { return fmt.Sprintf("%.3f", v) }

func (rep *report) markdown() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Codec measurement tables\n\nGenerated by `bench/codecs` (tag `measure`) from %s to %s, %s on %s, GOMAXPROCS=1, %d passes; times are each tile's median.\n\n",
		rep.Started, rep.Finished, rep.GoVersion, rep.GOARCH, rep.Runs)
	scenes := rep.scenes()

	// The corpus by class.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Tiles by class, %d×%d\n\nTiles of each class per scene (all frames), and the classification's and the swizzle's median time per tile.\n\n", size, size)
		head := append([]string{"Scene", "Frames"}, Classes...)
		head = append(head, "Classify µs/tile", "Swizzle µs/tile")
		var rows [][]string
		for _, sc := range scenes {
			r := []string{sc, fmt.Sprint(rep.Frames[sc])}
			n, cls, swz := 0, 0.0, 0.0
			for _, c := range Classes {
				k := 0
				for _, tc := range rep.Tiles {
					if tc.Size == size && tc.Scene == sc && tc.Class == c {
						k += tc.Tiles
						cls += tc.ClassifyNs
						swz += tc.SwizzleNs
					}
				}
				n += k
				r = append(r, fmt.Sprint(k))
			}
			r = append(r, f2(cls/1e3/float64(max(1, n))), f2(swz/1e3/float64(max(1, n))))
			rows = append(rows, r)
		}
		table(&b, head, rows)
	}

	// Lossless by class.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Lossless by class, %d×%d\n\nBits per pixel, then encode and decode µs per tile, over all scenes.\n\n", size, size)
		head := []string{"Codec"}
		for _, c := range Classes {
			head = append(head, c+" bpp", c+" enc", c+" dec")
		}
		var rows [][]string
		for _, codec := range append(rep.lossless(), "raw RGB", "raw BGRX") {
			src := rep.Rows
			if strings.HasPrefix(codec, "raw ") {
				src = rep.Raw
			}
			r := []string{codec}
			for _, c := range Classes {
				s := rep.sum(src, size, codec, every, is(c))
				r = append(r, f2(s.bpp()), f1(s.encUs()), f1(s.decUs()))
			}
			rows = append(rows, r)
		}
		table(&b, head, rows)
	}

	// Lossless per scene, on the tiles they would carry.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Lossless per scene, %d×%d\n\nOn each scene's tiles of up to 256 colours: KiB per frame, then encode and decode ms per frame. Mismatches would be listed after a slash.\n\n", size, size)
		head := append([]string{"Codec"}, scenes...)
		var rows [][]string
		for _, codec := range rep.lossless() {
			r := []string{codec}
			for _, sc := range scenes {
				s := rep.sum(rep.Rows, size, codec, is(sc), lowColour)
				fr := float64(rep.Frames[sc])
				cell := fmt.Sprintf("%.1f · %.2f · %.2f", float64(s.Bytes)/1024/fr, s.EncodeNs/1e6/fr, s.DecodeNs/1e6/fr)
				if s.Mismatch > 0 {
					cell += fmt.Sprintf(" / %d", s.Mismatch)
				}
				r = append(r, cell)
			}
			rows = append(rows, r)
		}
		table(&b, head, rows)
	}

	// Lossy on photographic tiles.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Lossy on tiles above 256 colours, %d×%d\n\nAll scenes: bits per pixel, SSIM, encode and decode µs per tile.\n\n", size, size)
		head := []string{"Codec", "bpp", "SSIM", "enc µs", "dec µs"}
		var rows [][]string
		for _, codec := range rep.Codecs {
			if !strings.Contains(codec, " q") {
				continue
			}
			s := rep.sum(rep.Rows, size, codec, every, highColour)
			rows = append(rows, []string{codec, f2(s.bpp()), f3(s.ssim()), f1(s.encUs()), f1(s.decUs())})
		}
		table(&b, head, rows)
	}

	// Lossy per scene at equal SSIM.
	targets := []float64{0.85, 0.90, 0.95}
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Lossy at equal SSIM, %d×%d\n\nKiB per frame of each scene's tiles above 256 colours at an SSIM target, interpolated between the measured qualities, with the quality that reaches it; a dash where no measured quality does.\n\n", size, size)
		head := []string{"Scene", "Family"}
		for _, tg := range targets {
			head = append(head, fmt.Sprintf("SSIM %.2f", tg))
		}
		var rows [][]string
		for _, sc := range append(scenes, "all frames, total") {
			scf := is(sc)
			frames := float64(rep.Frames[sc])
			if sc == "all frames, total" {
				scf, frames = every, 1
			}
			if rep.sum(rep.Rows, size, rep.Codecs[0], scf, highColour).Tiles == 0 {
				continue
			}
			for _, fam := range rep.families() {
				r := []string{sc, fam}
				for _, tg := range targets {
					r = append(r, rep.atSSIM(size, fam, scf, tg, frames))
				}
				rows = append(rows, r)
			}
		}
		table(&b, head, rows)
	}

	// What a tile costs at the least: solid tiles.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Solid tiles, %d×%d\n\nBytes per tile of one colour, which is each format's fixed cost, and encode µs per tile.\n\n", size, size)
		var rows [][]string
		for _, codec := range rep.Codecs {
			if q := strings.Index(codec, " q"); q >= 0 && !strings.HasSuffix(codec, " q30") && !strings.HasSuffix(codec, " q90") {
				continue
			}
			s := rep.sum(rep.Rows, size, codec, every, is("1"))
			if s.Tiles == 0 {
				continue
			}
			rows = append(rows, []string{codec, f1(float64(s.Bytes) / float64(s.Tiles)), f1(s.encUs())})
		}
		table(&b, []string{"Codec", "Bytes/tile", "enc µs"}, rows)
	}

	// Lossy codecs on text: SSIM by class.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## SSIM by class, %d×%d\n\nWhat each lossy codec does to each class, over all scenes, at three qualities.\n\n", size, size)
		head := append([]string{"Codec"}, Classes...)
		var rows [][]string
		for _, fam := range rep.families() {
			for _, q := range []int{30, 70, 90} {
				codec := fmt.Sprintf("%s q%d", fam, q)
				r := []string{codec}
				for _, c := range Classes {
					r = append(r, f3(rep.sum(rep.Rows, size, codec, every, is(c)).ssim()))
				}
				rows = append(rows, r)
			}
		}
		table(&b, head, rows)
	}

	// Pixel layouts: raw pixels deflated in each byte order.
	for _, size := range rep.Sizes {
		fmt.Fprintf(&b, "## Raw pixel layouts, %d×%d\n\nRaw pixels deflated at level 1 in each byte order: bits per pixel and deflate µs per tile, by class.\n\n", size, size)
		head := []string{"Layout"}
		for _, c := range Classes {
			head = append(head, c+" bpp", c+" µs")
		}
		var rows [][]string
		for _, l := range rawLayouts {
			r := []string{l}
			for _, c := range Classes {
				s := rep.sum(rep.Raw, size, "raw "+l, every, is(c))
				r = append(r, f2(s.bpp()), f1(s.encUs()))
			}
			rows = append(rows, r)
		}
		table(&b, head, rows)
	}

	// The pipeline's mix per scene and tile size.
	b.WriteString("## The pipeline's mix per scene\n\nKiB and encode ms per frame with the lossless codec for tiles of up to 256 colours and a lossy one above, at each tile size.\n\n")
	head := []string{"Scene", "Mix"}
	for _, size := range rep.Sizes {
		head = append(head, fmt.Sprintf("%d KiB", size), fmt.Sprintf("%d ms", size))
	}
	var rows [][]string
	for _, sc := range scenes {
		for _, mix := range [][2]string{
			{"pal+flate1", "jpeg q50"}, {"pal+flate1", "jpeg q70"}, {"pal+flate1", "jpeg q90"},
			{"pal+flate1", "jpegn q70"}, {"pal+flate1", "webp-vpx0 q70"}, {"pal+flate1", "webp-vpx4 q70"},
			{"png1", "jpeg q70"}, {"webpll-vpx4", "webp-vpx4 q70"},
		} {
			r := []string{sc, mix[0] + " + " + mix[1]}
			for _, size := range rep.Sizes {
				lo := rep.sum(rep.Rows, size, mix[0], is(sc), lowColour)
				hi := rep.sum(rep.Rows, size, mix[1], is(sc), highColour)
				fr := float64(rep.Frames[sc])
				r = append(r, f1(float64(lo.Bytes+hi.Bytes)/1024/fr), f2((lo.EncodeNs+hi.EncodeNs)/1e6/fr))
			}
			rows = append(rows, r)
		}
	}
	table(&b, head, rows)

	// Motion: every codec on whole frames.
	if rep.Frames["motion"] > 0 {
		for _, size := range rep.Sizes {
			fmt.Fprintf(&b, "## The motion scene, %d×%d\n\nEvery codec on every tile of the plasma: KiB per frame, SSIM, encode ms per frame.\n\n", size, size)
			var rows [][]string
			for _, codec := range rep.Codecs {
				s := rep.sum(rep.Rows, size, codec, is("motion"), every)
				fr := float64(rep.Frames["motion"])
				rows = append(rows, []string{codec, f1(float64(s.Bytes) / 1024 / fr), f3(s.ssim()), f2(s.EncodeNs / 1e6 / fr)})
			}
			table(&b, []string{"Codec", "KiB/frame", "SSIM", "enc ms/frame"}, rows)
		}
	}

	// Whole frames.
	if len(rep.Whole) > 0 {
		b.WriteString("## Lossy codecs on whole frames and rows\n\nEach frame encoded as one image, and the photograph's and the motion's frames as 16 rows of 64-pixel tiles: KiB, SSIM, encode and decode ms per frame.\n\n")
		var rows [][]string
		for _, w := range rep.Whole {
			fr := float64(w.Frames)
			rows = append(rows, []string{w.Scene, w.Unit, w.Codec, f1(float64(w.Bytes) / 1024 / fr), f3(w.SSIMSum / fr), f2(w.EncodeNs / 1e6 / fr), f2(w.DecodeNs / 1e6 / fr)})
		}
		table(&b, []string{"Scene", "Unit", "Codec", "KiB/frame", "SSIM", "enc ms", "dec ms"}, rows)
	}

	// Damage.
	b.WriteString("## Damage at each tile size\n\nThe tiles a change touches, their pixels and their bytes in the mix " + *pipeLL + " + " + *pipeLossy + ".\n\n")
	rows = nil
	for _, d := range rep.Damage {
		rows = append(rows, []string{d.Case, fmt.Sprint(d.Size), fmt.Sprint(d.Tiles), fmt.Sprint(d.Pixels), f1(float64(d.Bytes) / 1024)})
	}
	table(&b, []string{"Change", "Tile", "Tiles", "Pixels", "KiB"}, rows)
	return b.String()
}

// atSSIM interpolates a family's bytes per frame at an SSIM target over
// the tiles that scene selects, linearly between the two qualities that
// bracket it.
func (rep *report) atSSIM(size int, fam string, scene func(string) bool, target, frames float64) string {
	type point struct {
		q         int
		kib, ssim float64
	}
	var pts []point
	for _, q := range Qualities {
		codec := fmt.Sprintf("%s q%d", fam, q)
		if !slices.Contains(rep.Codecs, codec) {
			continue
		}
		s := rep.sum(rep.Rows, size, codec, scene, highColour)
		pts = append(pts, point{q, float64(s.Bytes) / 1024 / frames, s.ssim()})
	}
	for i := 1; i < len(pts); i++ {
		a, c := pts[i-1], pts[i]
		if (a.ssim <= target && target <= c.ssim) || (c.ssim <= target && target <= a.ssim) {
			t := 0.0
			if c.ssim != a.ssim {
				t = (target - a.ssim) / (c.ssim - a.ssim)
			}
			return fmt.Sprintf("%.1f (q%.0f)", a.kib+t*(c.kib-a.kib), float64(a.q)+t*float64(c.q-a.q))
		}
	}
	if len(pts) > 0 && pts[0].ssim >= target {
		return fmt.Sprintf("≤%.1f (q%d)", pts[0].kib, pts[0].q)
	}
	return "–"
}
