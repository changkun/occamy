// sender returns the peer that sends messages of type t, from its range.
func sender(t protocol.Type) string {
	switch t >> 8 {
	case 0:
		return "either"
	case 1:
		return "client"
	case 2:
		return "server"
	}
	return "unknown"
}

// receivers returns the registries of the peers that receive messages
// from the named sender.
func receivers(from string) []*protocol.Registry {
	switch from {
	case "client":
		return []*protocol.Registry{protocol.ClientMessages()}
	case "server":
		return []*protocol.Registry{protocol.ServerMessages()}
	}
	return []*protocol.Registry{protocol.ClientMessages(), protocol.ServerMessages()}
}

// msgBuilder builds a message field by field, for malformed messages.
type msgBuilder []byte

func build(t protocol.Type) msgBuilder { return protocol.AppendHeader(nil, protocol.Header{Type: t}) }

func (b msgBuilder) u8(v uint8) msgBuilder   { return protocol.AppendUint8(b, v) }
func (b msgBuilder) u16(v uint16) msgBuilder { return protocol.AppendUint16(b, v) }
func (b msgBuilder) u32(v uint32) msgBuilder { return protocol.AppendUint32(b, v) }
func (b msgBuilder) str(s string) msgBuilder { return protocol.AppendString(b, s) }
func (b msgBuilder) raw(p ...byte) msgBuilder {
	return append(b, p...)
}
func (b msgBuilder) bytes(p []byte) msgBuilder { return protocol.AppendBytes(b, p) }

// cap appends a capability entry.
func (b msgBuilder) cap(id uint16, value ...byte) msgBuilder { return b.u16(id).bytes(value) }

// helloWith returns a hello whose capability list has n entries, which
// the caller appends.
func helloWith(n uint16) msgBuilder {
	return build(protocol.TypeHello).u16(1).u16(0).u16(0).u16(0).u16(0).u8(0).str("").u16(n)
}

// tile returns a tile with the given size, codec, slot and payload.
func tile(w, h uint16, codec uint8, slot uint16, payload []byte) msgBuilder {
	return build(protocol.TypeTile).u32(1).u16(0).u16(0).u16(w).u16(h).u8(codec).u16(slot).bytes(payload)
}

// cursor returns a cursor with the given hot spot, size, codec and
// payload.
func cursor(x, y, w, h uint16, codec uint8, payload []byte) msgBuilder {
	return build(protocol.TypeCursor).u16(x).u16(y).u16(w).u16(h).u8(codec).bytes(payload)
}

