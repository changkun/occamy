type messagesGolden struct {
	Comment      string                 `json:"comment"`
	Limits       limitsVector           `json:"limits"`
	Messages     []messageVector        `json:"messages"`
	Invalid      []invalidMessageVector `json:"invalid"`
	HelloQuery   []helloQueryVector     `json:"hello_query"`
	Tokens       []tokenVector          `json:"tokens"`
	Subprotocols []subprotocolVector    `json:"subprotocols"`
}

type limitsVector struct {
	MaxMessageSize int `json:"max_message_size"`
	MaxTextureSize int `json:"max_texture_size"`
	CacheSlots     int `json:"cache_slots"`
}

func (l limitsVector) limits() protocol.Limits {
	return protocol.Limits{MaxMessageSize: l.MaxMessageSize, MaxTextureSize: l.MaxTextureSize, CacheSlots: l.CacheSlots}
}

// goldenLimits are the limits every vector decodes under unless it has
// its own.
var goldenLimits = limitsVector{MaxMessageSize: protocol.DefaultMaxMessageSize, MaxTextureSize: 4096, CacheSlots: 1024}

type messageVector struct {
	Name    string          `json:"name"`
	Message string          `json:"message"`
	Type    uint16          `json:"type"`
	From    string          `json:"from"`
	Fields  json.RawMessage `json:"fields"`
	Hex     string          `json:"hex"`
}

type invalidMessageVector struct {
	Name   string        `json:"name"`
	From   string        `json:"from"`
	Limits *limitsVector `json:"limits,omitempty"`
	Hex    string        `json:"hex"`
	Error  string        `json:"error"`
}

// helloQueryVector is a value of the hello query parameter and the hello
// message it decodes to, or the error it fails with.
type helloQueryVector struct {
	Name  string `json:"name"`
	Query string `json:"query"`
	Hex   string `json:"hex,omitempty"`
	Error string `json:"error,omitempty"`
}

// tokenVector is a token and the subprotocol that carries it.
type tokenVector struct {
	Token       string `json:"token"`
	Subprotocol string `json:"subprotocol"`
}

// subprotocolVector is the values of the Sec-WebSocket-Protocol header
// lines of an upgrade request, and the token they offer or the error.
type subprotocolVector struct {
	Name    string   `json:"name"`
	Offered []string `json:"offered"`
	Token   string   `json:"token"`
	Error   string   `json:"error,omitempty"`
}

// namedMessage is a message vector's name and value.
type namedMessage struct {
	name string
	msg  protocol.Message
}

// pixels returns n bytes of a repeating pattern, for payloads.
func pixels(n int) []byte {
	p := make([]byte, n)
	for i := range p {
		p[i] = byte(i * 37)
	}
	return p
}

