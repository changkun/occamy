// invalidHelloQueries are values of the hello query parameter that fail
// to decode.
func invalidHelloQueries(t testing.TB) []helloQueryVector {
	valid, err := protocol.EncodeHelloQuery(webHello)
	if err != nil {
		t.Fatal(err)
	}
	welcome, err := protocol.EncodeHelloQuery(protocol.Hello{})
	if err != nil {
		t.Fatal(err)
	}
	// Turn the hello's type into welcome's: 01 01 becomes 01 02, so the
	// first characters change from "AQE" to "AQI".
	welcome = "AQI" + welcome[3:]
	return []helloQueryVector{
		{Name: "empty", Query: ""},
		{Name: "padding", Query: valid + strings.Repeat("=", (4-len(valid)%4)%4+4)},
		{Name: "standard alphabet", Query: strings.NewReplacer("-", "+", "_", "/").Replace(valid) + "+/"},
		{Name: "line break", Query: valid[:8] + "\n" + valid[8:]},
		{Name: "trailing bits", Query: "AQEAAAAAAAAAAAAAAAAAAAAAAB"},
		{Name: "one character too many for base64", Query: "AQEAA"},
		{Name: "not a hello", Query: welcome},
		{Name: "too large", Query: strings.Repeat("A", 2732)},
		{Name: "truncated", Query: valid[:12]},
	}
}

// vectorsMessages builds the message vectors from their values.
func vectorsMessages(t testing.TB) messagesGolden {
	g := messagesGolden{Comment: messagesComment, Limits: goldenLimits}
	for _, nm := range messageValues() {
		fields, err := json.Marshal(toJSON(reflect.ValueOf(nm.msg).Elem()))
		if err != nil {
			t.Fatalf("%s: %v", nm.name, err)
		}
		g.Messages = append(g.Messages, messageVector{
			Name:    nm.name,
			Message: nm.msg.Type().String(),
			Type:    uint16(nm.msg.Type()),
			From:    sender(nm.msg.Type()),
			Fields:  fields,
			Hex:     hex.EncodeToString(nm.msg.Append(nil)),
		})
	}

	g.Invalid = invalidMessages()
	for i, v := range g.Invalid {
		g.Invalid[i].Error = errorName(decodeInvalidMessage(t, g.Limits, v))
	}

	for _, h := range []namedMessage{{"web client", &webHello}, {"nothing", &protocol.Hello{}}} {
		q, err := protocol.EncodeHelloQuery(*h.msg.(*protocol.Hello))
		if err != nil {
			t.Fatal(err)
		}
		g.HelloQuery = append(g.HelloQuery, helloQueryVector{Name: h.name, Query: q, Hex: hex.EncodeToString(h.msg.Append(nil))})
	}
	for _, v := range invalidHelloQueries(t) {
		_, err := protocol.DecodeHelloQuery(v.Query)
		v.Error = errorName(err)
		g.HelloQuery = append(g.HelloQuery, v)
	}

	for _, token := range []string{"eyJhbGciOiJFZERTQSJ9.eyJzdWIiOiJhbGljZSJ9.c2ln", "opaque token/with+symbols=", "é"} {
		g.Tokens = append(g.Tokens, tokenVector{Token: token, Subprotocol: protocol.TokenSubprotocol(token)})
	}

	tok := protocol.TokenSubprotocol("secret")
	g.Subprotocols = []subprotocolVector{
		{Name: "token", Offered: []string{"occamy.v1, " + tok}},
		{Name: "token on its own line", Offered: []string{"occamy.v1", tok}},
		{Name: "no token", Offered: []string{"occamy.v1"}},
		{Name: "other subprotocols", Offered: []string{"chat,occamy.v2, occamy.v1 ,\t" + tok}},
		{Name: "occamy.v1 not offered", Offered: []string{tok}},
		{Name: "nothing offered", Offered: []string{}},
		{Name: "two tokens", Offered: []string{"occamy.v1", tok, protocol.TokenSubprotocol("other")}},
		{Name: "empty token", Offered: []string{"occamy.v1, occamy.v1.token."}},
		{Name: "token with padding", Offered: []string{"occamy.v1, " + tok + "="}},
		{Name: "token with the standard alphabet", Offered: []string{"occamy.v1, occamy.v1.token.c2Vj+mV0"}},
	}
	for i, v := range g.Subprotocols {
		token, err := protocol.TokenFromSubprotocols(v.Offered)
		g.Subprotocols[i].Token, g.Subprotocols[i].Error = token, errorName(err)
	}
	return g
}

// decodeInvalidMessage decodes an invalid vector with every receiver of
// its sender's messages, and returns the error, which must be the same
// for each.
func decodeInvalidMessage(t testing.TB, def limitsVector, v invalidMessageVector) error {
	raw, err := hex.DecodeString(v.Hex)
	if err != nil {
		t.Fatalf("%s: %v", v.Name, err)
	}
	l := def
	if v.Limits != nil {
		l = *v.Limits
	}
	var first error
	for i, r := range receivers(v.From) {
		m, err := protocol.Decode(raw, r, l.limits())
		if m != nil {
			t.Fatalf("invalid %q decodes to %+v", v.Name, m)
		}
		if i == 0 {
			first = err
		} else if errorName(err) != errorName(first) {
			t.Fatalf("invalid %q: %v from one receiver, %v from another", v.Name, first, err)
		}
	}
	return first
}

// TestGoldenMessages checks that the package encodes the values of the
// message vectors to their bytes and decodes the bytes to the values,
// that invalid vectors fail as recorded, and that the file is up to date.
// With -update it rewrites the file.
func TestGoldenMessages(t *testing.T) {
	want, err := marshalGolden(vectorsMessages(t))
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile(messagesFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(messagesFile)
	if err != nil {
		t.Fatalf("%v (run go test -run TestGoldenMessages -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is out of date (run go test -run TestGoldenMessages -update):\n%s", messagesFile, firstDiff(got, want))
	}

	var g messagesGolden
	if err := json.Unmarshal(got, &g); err != nil {
		t.Fatal(err)
	}
	checkGoldenMessages(t, g)
}

// checkGoldenMessages checks every vector in g both ways.
func checkGoldenMessages(t *testing.T, g messagesGolden) {
	types := map[protocol.Type]bool{}
	for _, v := range g.Messages {
		raw, err := hex.DecodeString(v.Hex)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		typ := protocol.Type(v.Type)
		types[typ] = true
		if typ.String() != v.Message || sender(typ) != v.From {
			t.Errorf("message %q: type %#04x is %s from %s, the file says %s from %s", v.Name, v.Type, typ, sender(typ), v.Message, v.From)
		}

		// Fields to bytes.
		m := protocol.New(typ)
		if m == nil {
			t.Fatalf("message %q: no message of type %#04x", v.Name, v.Type)
		}
		var fields any
		if err := json.Unmarshal(v.Fields, &fields); err != nil {
			t.Fatalf("message %q: %v", v.Name, err)
		}
		if err := fromJSON(reflect.ValueOf(m).Elem(), fields); err != nil {
			t.Fatalf("message %q: %v", v.Name, err)
		}
		if enc := m.Append(nil); !bytes.Equal(enc, raw) {
			t.Errorf("message %q: encodes to %x, want %s", v.Name, enc, v.Hex)
		}

		// Bytes to fields, with every receiver of the sender's messages.
		for _, r := range receivers(v.From) {
			dec, err := protocol.Decode(raw, r, g.Limits.limits())
			if err != nil {
				t.Errorf("message %q: %v", v.Name, err)
				continue
			}
			enc, err := json.Marshal(toJSON(reflect.ValueOf(dec).Elem()))
			if err != nil {
				t.Fatal(err)
			}
			var got any
			if err := json.Unmarshal(enc, &got); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(got, fields) {
				t.Errorf("message %q: decodes to %s, want %s", v.Name, enc, v.Fields)
			}
		}
	}
	for _, typ := range allTypes() {
		if !types[typ] {
			t.Errorf("no vector for %s (%#04x)", typ, uint16(typ))
		}
	}

	for _, v := range g.Invalid {
		if got := errorName(decodeInvalidMessage(t, g.Limits, v)); got != v.Error || got == "" {
			t.Errorf("invalid %q: fails with %q, want %q", v.Name, got, v.Error)
		}
	}

	for _, v := range g.HelloQuery {
		h, err := protocol.DecodeHelloQuery(v.Query)
		if got := errorName(err); got != v.Error {
			t.Errorf("hello query %q: fails with %q, want %q", v.Name, got, v.Error)
			continue
		}
		if v.Error != "" {
			continue
		}
		if enc := hex.EncodeToString(h.Append(nil)); enc != v.Hex {
			t.Errorf("hello query %q: decodes to %s, want %s", v.Name, enc, v.Hex)
		}
		if q, err := protocol.EncodeHelloQuery(h); err != nil || q != v.Query {
			t.Errorf("hello query %q: encodes to %q, %v, want %q", v.Name, q, err, v.Query)
		}
	}

	for _, v := range g.Tokens {
		if got := protocol.TokenSubprotocol(v.Token); got != v.Subprotocol {
			t.Errorf("token %q: subprotocol %q, want %q", v.Token, got, v.Subprotocol)
		}
		if got, err := protocol.TokenFromSubprotocols([]string{protocol.Subprotocol, v.Subprotocol}); err != nil || got != v.Token {
			t.Errorf("token %q: parsed as %q, %v", v.Token, got, err)
		}
	}
	for _, v := range g.Subprotocols {
		token, err := protocol.TokenFromSubprotocols(v.Offered)
		if token != v.Token || errorName(err) != v.Error {
			t.Errorf("subprotocols %q: %q, %v, want %q, %q", v.Name, token, err, v.Token, v.Error)
		}
	}
}

// allTypes returns every v1 message type.
func allTypes() []protocol.Type {
	var types []protocol.Type
	for t := range protocol.Type(0x0300) {
		if protocol.New(t) != nil {
			types = append(types, t)
		}
	}
	return types
}

// member is a member of a JSON object.
type member struct {
	key   string
	value any
}

// object is a JSON object whose members keep their order.
type object []member

func (o object) MarshalJSON() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteByte('{')
	for i, m := range o {
		if i > 0 {
			buf.WriteByte(',')
		}
		k, err := json.Marshal(m.key)
		if err != nil {
			return nil, err
		}
		v, err := json.Marshal(m.value)
		if err != nil {
			return nil, err
		}
		buf.Write(k)
		buf.WriteByte(':')
		buf.Write(v)
	}
	buf.WriteByte('}')
	return buf.Bytes(), nil
}

var bytesType = reflect.TypeFor[[]byte]()

// toJSON returns the JSON value of a message or a field: integers as
// decimal strings, byte strings as hex, slices as arrays and structs as
// objects with snake_case keys in field order.
func toJSON(v reflect.Value) any {
	switch v.Kind() {
	case reflect.Bool:
		return v.Bool()
	case reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return strconv.FormatUint(v.Uint(), 10)
	case reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(v.Int(), 10)
	case reflect.String:
		return v.String()
	case reflect.Slice:
		if v.Type() == bytesType {
			return hex.EncodeToString(v.Bytes())
		}
		a := make([]any, v.Len())
		for i := range a {
			a[i] = toJSON(v.Index(i))
		}
		return a
	case reflect.Struct:
		o := object{}
		for i := range v.NumField() {
			o = append(o, member{snake(v.Type().Field(i).Name), toJSON(v.Field(i))})
		}
		return o
	}
	panic("toJSON: unexpected kind " + v.Kind().String())
}

// fromJSON sets v from j, a value that toJSON returned, decoded by
// encoding/json.
func fromJSON(v reflect.Value, j any) error {
	switch v.Kind() {
	case reflect.Bool:
		b, ok := j.(bool)
		if !ok {
			return fmt.Errorf("%v is not a boolean", j)
		}
		v.SetBool(b)
	case reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		s, _ := j.(string)
		n, err := strconv.ParseUint(s, 10, v.Type().Bits())
		if err != nil {
			return err
		}
		v.SetUint(n)
	case reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		s, _ := j.(string)
		n, err := strconv.ParseInt(s, 10, v.Type().Bits())
		if err != nil {
			return err
		}
		v.SetInt(n)
	case reflect.String:
		s, ok := j.(string)
		if !ok {
			return fmt.Errorf("%v is not a string", j)
		}
		v.SetString(s)
	case reflect.Slice:
		if v.Type() == bytesType {
			s, _ := j.(string)
			p, err := hex.DecodeString(s)
			if err != nil {
				return err
			}
			v.SetBytes(p)
			return nil
		}
		a, ok := j.([]any)
		if !ok {
			return fmt.Errorf("%v is not an array", j)
		}
		if len(a) == 0 {
			v.SetZero()
			return nil
		}
		s := reflect.MakeSlice(v.Type(), len(a), len(a))
		for i := range a {
			if err := fromJSON(s.Index(i), a[i]); err != nil {
				return err
			}
		}
		v.Set(s)
	case reflect.Struct:
		o, ok := j.(map[string]any)
		if !ok {
			return fmt.Errorf("%v is not an object", j)
		}
		if len(o) != v.NumField() {
			return fmt.Errorf("%d members for %d fields of %s", len(o), v.NumField(), v.Type())
		}
		for i := range v.NumField() {
			key := snake(v.Type().Field(i).Name)
			m, ok := o[key]
			if !ok {
				return fmt.Errorf("no member %q for %s", key, v.Type())
			}
			if err := fromJSON(v.Field(i), m); err != nil {
				return fmt.Errorf("%s: %w", key, err)
			}
		}
	default:
		return fmt.Errorf("unexpected kind %s", v.Kind())
	}
	return nil
}

// snake turns a Go field name into snake_case: FrameID becomes frame_id,
// HotX hot_x and MIME mime.
func snake(name string) string {
	r := []rune(name)
	var b strings.Builder
	for i, c := range r {
		if i > 0 && unicode.IsUpper(c) && (unicode.IsLower(r[i-1]) || i+1 < len(r) && unicode.IsLower(r[i+1])) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToLower(c))
	}
	return b.String()
}
