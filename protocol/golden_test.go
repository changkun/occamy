var update = flag.Bool("update", false, "rewrite the golden vectors in testdata")

// goldenFile holds vectors for the header and the primitives. Other
// implementations of the protocol, such as the web client's, check their
// codecs against it, and docs/protocol.md is checked against it.
var goldenFile = filepath.Join("testdata", "framing.json")

const goldenComment = "Occamy protocol v1 framing vectors, generated by " +
	"`go test ./protocol -run TestGolden -update`. Hex is lowercase. " +
	"Integer values are decimal strings, so that 64-bit values survive " +
	"JavaScript numbers. Byte string values are hex. Invalid vectors fail " +
	"to decode with the named error. Dispatch vectors are whole messages " +
	"received by a peer that knows the registered types."

type golden struct {
	Comment  string           `json:"comment"`
	Header   []headerVector   `json:"header"`
	Integers []integerVector  `json:"integers"`
	Bytes    []bytesVector    `json:"bytes"`
	Strings  []stringVector   `json:"strings"`
	Invalid  []invalidVector  `json:"invalid"`
	Dispatch []dispatchVector `json:"dispatch"`
}

type headerVector struct {
	Name      string `json:"name"`
	Type      uint16 `json:"type"`
	Flags     uint16 `json:"flags"`
	Ignorable bool   `json:"ignorable"`
	Hex       string `json:"hex"`
}

type integerVector struct {
	Name  string `json:"name"`
	Kind  string `json:"kind"`
	Value string `json:"value"`
	Hex   string `json:"hex"`
}

type bytesVector struct {
	Name  string `json:"name"`
	Value string `json:"value"`
	Hex   string `json:"hex"`
}

type stringVector struct {
	Name  string `json:"name"`
	Value string `json:"value"`
	Hex   string `json:"hex"`
}

// invalidVector is a field, or for kind "message" a whole message
// checked against MaxMessageSize (the default if zero), that fails to
// decode.
type invalidVector struct {
	Name           string `json:"name"`
	Kind           string `json:"kind"`
	MaxMessageSize int    `json:"max_message_size,omitempty"`
	Hex            string `json:"hex"`
	Error          string `json:"error"`
}

// dispatchVector is a message and what a receiver that knows the
// registered types does with it: "decode", "skip" or "unsupported".
type dispatchVector struct {
	Name       string   `json:"name"`
	Registered []uint16 `json:"registered"`
	Hex        string   `json:"hex"`
	Action     string   `json:"action"`
}

// integerKinds maps a kind to its size in bits and whether it is signed.
var integerKinds = map[string]struct {
	bits   int
	signed bool
}{
	"uint8": {8, false}, "uint16": {16, false}, "uint32": {32, false}, "uint64": {64, false},
	"int8": {8, true}, "int16": {16, true}, "int32": {32, true}, "int64": {64, true},
}

func appendInteger(b []byte, kind, value string) ([]byte, error) {
	k, ok := integerKinds[kind]
	if !ok {
		return nil, fmt.Errorf("unknown kind %q", kind)
	}
	if k.signed {
		v, err := strconv.ParseInt(value, 10, k.bits)
		if err != nil {
			return nil, err
		}
		switch k.bits {
		case 8:
			return protocol.AppendInt8(b, int8(v)), nil
		case 16:
			return protocol.AppendInt16(b, int16(v)), nil
		case 32:
			return protocol.AppendInt32(b, int32(v)), nil
		}
		return protocol.AppendInt64(b, v), nil
	}
	v, err := strconv.ParseUint(value, 10, k.bits)
	if err != nil {
		return nil, err
	}
	switch k.bits {
	case 8:
		return protocol.AppendUint8(b, uint8(v)), nil
	case 16:
		return protocol.AppendUint16(b, uint16(v)), nil
	case 32:
		return protocol.AppendUint32(b, uint32(v)), nil
	}
	return protocol.AppendUint64(b, v), nil
}

// readInteger reads an integer of the given kind and formats it in
// decimal.
func readInteger(d *protocol.Decoder, kind string) string {
	switch kind {
	case "uint8":
		return strconv.FormatUint(uint64(d.ReadUint8()), 10)
	case "uint16":
		return strconv.FormatUint(uint64(d.ReadUint16()), 10)
	case "uint32":
		return strconv.FormatUint(uint64(d.ReadUint32()), 10)
	case "uint64":
		return strconv.FormatUint(d.ReadUint64(), 10)
	case "int8":
		return strconv.FormatInt(int64(d.ReadInt8()), 10)
	case "int16":
		return strconv.FormatInt(int64(d.ReadInt16()), 10)
	case "int32":
		return strconv.FormatInt(int64(d.ReadInt32()), 10)
	case "int64":
		return strconv.FormatInt(d.ReadInt64(), 10)
	}
	panic("unknown kind " + kind)
}

// errorName is the name of a decoding error in the vectors.
func errorName(err error) string {
	switch {
	case err == nil:
		return ""
	case errors.Is(err, protocol.ErrTruncated):
		return "truncated"
	case errors.Is(err, protocol.ErrTooLarge):
		return "too-large"
	case errors.Is(err, protocol.ErrInvalidUTF8):
		return "invalid-utf8"
	case errors.Is(err, protocol.ErrUnsupported):
		return "unsupported"
	case errors.Is(err, protocol.ErrTrailingData):
		return "trailing-data"
	}
	return err.Error()
}

// decodeInvalid decodes the field or message of an invalid vector and
// returns the error.
func decodeInvalid(v invalidVector, raw []byte) error {
	if v.Kind == "message" {
		_, _, err := protocol.Split(raw, protocol.Limits{MaxMessageSize: v.MaxMessageSize})
		return err
	}
	d := protocol.NewDecoder(raw)
	switch v.Kind {
	case "bytes":
		d.ReadBytes()
	case "string":
		d.ReadString()
	default:
		readInteger(d, v.Kind)
	}
	return d.Finish()
}

// dispatch returns what a receiver that knows the registered types does
// with msg.
func dispatch(registered []uint16, msg []byte) string {
	var r protocol.Registry
	for _, t := range registered {
		r.Register(protocol.Type(t), fmt.Sprintf("type-%d", t))
	}
	h, _, err := protocol.Split(msg, protocol.Limits{})
	if err != nil {
		return errorName(err)
	}
	ok, err := r.Accept(h)
	switch {
	case err != nil:
		return errorName(err)
	case ok:
		return "decode"
	}
	return "skip"
}

// vectors builds the golden vectors from their values.
func vectors(t testing.TB) golden {
	g := golden{Comment: goldenComment}

	for _, v := range []headerVector{
		{Name: "type 1", Type: 1},
		{Name: "byte order", Type: 0x0102, Flags: 0},
		{Name: "ignorable", Type: 0x0102, Flags: uint16(protocol.FlagIgnorable)},
		{Name: "largest type", Type: 0xffff},
		{Name: "reserved flags, not ignorable", Type: 3, Flags: 0xfffe},
		{Name: "all flags", Type: 3, Flags: 0xffff},
	} {
		h := protocol.Header{Type: protocol.Type(v.Type), Flags: protocol.Flags(v.Flags)}
		v.Ignorable = h.Ignorable()
		v.Hex = hex.EncodeToString(protocol.AppendHeader(nil, h))
		g.Header = append(g.Header, v)
	}

	for _, v := range []integerVector{
		{Name: "uint8 zero", Kind: "uint8", Value: "0"},
		{Name: "uint8 largest", Kind: "uint8", Value: "255"},
		{Name: "uint16 byte order", Kind: "uint16", Value: "258"},
		{Name: "uint16 largest", Kind: "uint16", Value: "65535"},
		{Name: "uint32 byte order", Kind: "uint32", Value: "16909060"},
		{Name: "uint32 largest", Kind: "uint32", Value: "4294967295"},
		{Name: "uint64 byte order", Kind: "uint64", Value: "72623859790382856"},
		{Name: "uint64 largest", Kind: "uint64", Value: "18446744073709551615"},
		{Name: "int8 smallest", Kind: "int8", Value: "-128"},
		{Name: "int8 minus one", Kind: "int8", Value: "-1"},
		{Name: "int8 largest", Kind: "int8", Value: "127"},
		{Name: "int16 smallest", Kind: "int16", Value: "-32768"},
		{Name: "int16 minus two", Kind: "int16", Value: "-2"},
		{Name: "int16 largest", Kind: "int16", Value: "32767"},
		{Name: "int32 smallest", Kind: "int32", Value: "-2147483648"},
		{Name: "int32 minus one", Kind: "int32", Value: "-1"},
		{Name: "int32 largest", Kind: "int32", Value: "2147483647"},
		{Name: "int64 smallest", Kind: "int64", Value: "-9223372036854775808"},
		{Name: "int64 minus one", Kind: "int64", Value: "-1"},
		{Name: "int64 largest", Kind: "int64", Value: "9223372036854775807"},
	} {
		raw, err := appendInteger(nil, v.Kind, v.Value)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		v.Hex = hex.EncodeToString(raw)
		g.Integers = append(g.Integers, v)
	}

	all := make([]byte, 256)
	for i := range all {
		all[i] = byte(i)
	}
	for _, v := range []struct {
		name  string
		value []byte
	}{
		{"empty", nil},
		{"one zero byte", []byte{0}},
		{"three bytes", []byte{1, 2, 3}},
		{"256 bytes, a length over one byte", all},
	} {
		g.Bytes = append(g.Bytes, bytesVector{
			Name:  v.name,
			Value: hex.EncodeToString(v.value),
			Hex:   hex.EncodeToString(protocol.AppendBytes(nil, v.value)),
		})
	}

	for _, v := range []stringVector{
		{Name: "empty", Value: ""},
		{Name: "ASCII", Value: "occamy.v1"},
		{Name: "two-byte code point", Value: "h\u00e9llo"},
		{Name: "three-byte code points", Value: "\u4e16\u754c"},
		{Name: "four-byte code point", Value: "\U0001f600"},
		{Name: "NUL", Value: "a\x00b"},
		{Name: "U+FFFD", Value: "\uFFFD"},
		{Name: "U+10FFFF", Value: "\U0010ffff"},
	} {
		v.Hex = hex.EncodeToString(protocol.AppendString(nil, v.Value))
		g.Strings = append(g.Strings, v)
	}

	g.Invalid = []invalidVector{
		{Name: "empty message", Kind: "message", Hex: ""},
		{Name: "message shorter than a header", Kind: "message", Hex: "010000"},
		{Name: "message over the maximum size", Kind: "message", MaxMessageSize: 8, Hex: "010000000102030405"},
		{Name: "uint16 with one byte", Kind: "uint16", Hex: "01"},
		{Name: "uint32 with three bytes", Kind: "uint32", Hex: "010203"},
		{Name: "uint64 with seven bytes", Kind: "uint64", Hex: "01020304050607"},
		{Name: "int64 with no bytes", Kind: "int64", Hex: ""},
		{Name: "bytes with a short length", Kind: "bytes", Hex: "010000"},
		{Name: "bytes longer than the message", Kind: "bytes", Hex: "0300000001ff"},
		{Name: "bytes with the largest length", Kind: "bytes", Hex: "ffffffff00"},
		{Name: "string longer than the message", Kind: "string", Hex: "0200000061"},
		{Name: "string with a continuation byte", Kind: "string", Hex: "0100000080"},
		{Name: "string with byte ff", Kind: "string", Hex: "02000000ff61"},
		{Name: "string with an overlong encoding", Kind: "string", Hex: "02000000c0af"},
		{Name: "string with a surrogate", Kind: "string", Hex: "03000000eda080"},
		{Name: "string above U+10FFFF", Kind: "string", Hex: "04000000f4908080"},
		{Name: "string with a cut code point", Kind: "string", Hex: "02000000e282ac"},
	}
	for i, v := range g.Invalid {
		raw, err := hex.DecodeString(v.Hex)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		g.Invalid[i].Error = errorName(decodeInvalid(v, raw))
	}

	g.Dispatch = []dispatchVector{
		{Name: "known type", Registered: []uint16{1}, Hex: "01000000"},
		{Name: "known type marked ignorable", Registered: []uint16{1}, Hex: "010001000a0b"},
		{Name: "unknown type", Registered: []uint16{1}, Hex: "02000000"},
		{Name: "unknown type marked ignorable", Registered: []uint16{1}, Hex: "020001000a0b"},
		{Name: "unknown type with reserved flags only", Registered: []uint16{1}, Hex: "0200feff"},
		{Name: "unknown type with all flags", Registered: []uint16{1}, Hex: "0200ffff"},
		{Name: "type 0", Registered: []uint16{1}, Hex: "00000000"},
	}
	for i, v := range g.Dispatch {
		raw, err := hex.DecodeString(v.Hex)
		if err != nil {
			t.Fatalf("%s: %v", v.Name, err)
		}
		g.Dispatch[i].Action = dispatch(v.Registered, raw)
	}
	return g
}

func marshalGolden(g golden) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(g); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// TestGolden checks that the package encodes the golden vectors' values
// to their bytes, and decodes their bytes to their values, and that the
// file has every vector. With -update it rewrites the file.
func TestGolden(t *testing.T) {
	want, err := marshalGolden(vectors(t))
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile(goldenFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(goldenFile)
	if err != nil {
		t.Fatalf("%v (run go test -run TestGolden -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is out of date (run go test -run TestGolden -update):\n%s", goldenFile, firstDiff(got, want))
	}

	var g golden
	if err := json.Unmarshal(got, &g); err != nil {
		t.Fatal(err)
	}
	checkGolden(t, g)
}

// checkGolden decodes every vector in g and checks it both ways.
func checkGolden(t *testing.T, g golden) {
	decode := func(name, s string) []byte {
		raw, err := hex.DecodeString(s)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		return raw
	}
	for _, v := range g.Header {
		raw := decode(v.Name, v.Hex)
		h, body, err := protocol.Split(raw, protocol.Limits{})
		want := protocol.Header{Type: protocol.Type(v.Type), Flags: protocol.Flags(v.Flags)}
		if err != nil || h != want || len(body) != 0 || h.Ignorable() != v.Ignorable {
			t.Errorf("header %q: decodes to %+v, %x, %v", v.Name, h, body, err)
		}
		if enc := protocol.AppendHeader(nil, want); !bytes.Equal(enc, raw) {
			t.Errorf("header %q: encodes to %x, want %s", v.Name, enc, v.Hex)
		}
	}
	for _, v := range g.Integers {
		raw := decode(v.Name, v.Hex)
		d := protocol.NewDecoder(raw)
		if got := readInteger(d, v.Kind); got != v.Value || d.Finish() != nil {
			t.Errorf("integer %q: decodes to %s, %v", v.Name, got, d.Finish())
		}
		if enc, err := appendInteger(nil, v.Kind, v.Value); err != nil || !bytes.Equal(enc, raw) {
			t.Errorf("integer %q: encodes to %x, %v, want %s", v.Name, enc, err, v.Hex)
		}
	}
	for _, v := range g.Bytes {
		raw, value := decode(v.Name, v.Hex), decode(v.Name, v.Value)
		d := protocol.NewDecoder(raw)
		if got := d.ReadBytes(); !bytes.Equal(got, value) || d.Finish() != nil {
			t.Errorf("bytes %q: decodes to %x, %v", v.Name, got, d.Finish())
		}
		if enc := protocol.AppendBytes(nil, value); !bytes.Equal(enc, raw) {
			t.Errorf("bytes %q: encodes to %x, want %s", v.Name, enc, v.Hex)
		}
	}
	for _, v := range g.Strings {
		raw := decode(v.Name, v.Hex)
		d := protocol.NewDecoder(raw)
		if got := d.ReadString(); got != v.Value || d.Finish() != nil {
			t.Errorf("string %q: decodes to %q, %v", v.Name, got, d.Finish())
		}
		if enc := protocol.AppendString(nil, v.Value); !bytes.Equal(enc, raw) {
			t.Errorf("string %q: encodes to %x, want %s", v.Name, enc, v.Hex)
		}
	}
	for _, v := range g.Invalid {
		if got := errorName(decodeInvalid(v, decode(v.Name, v.Hex))); got != v.Error || got == "" {
			t.Errorf("invalid %q: fails with %q, want %q", v.Name, got, v.Error)
		}
	}
	for _, v := range g.Dispatch {
		if got := dispatch(v.Registered, decode(v.Name, v.Hex)); got != v.Action {
			t.Errorf("dispatch %q: %s, want %s", v.Name, got, v.Action)
		}
	}
}

// firstDiff describes the first line where got and want differ.
func firstDiff(got, want []byte) string {
	g, w := strings.Split(string(got), "\n"), strings.Split(string(want), "\n")
	for i := 0; i < len(g) || i < len(w); i++ {
		var gl, wl string
		if i < len(g) {
			gl = g[i]
		}
		if i < len(w) {
			wl = w[i]
		}
		if gl != wl {
			return fmt.Sprintf("line %d:\n  file: %s\n  want: %s", i+1, gl, wl)
		}
	}
	return "no difference"
}
