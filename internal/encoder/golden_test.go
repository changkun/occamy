// encodeCase encodes c with an encoder that sends its codec.
func encodeCase(t testing.TB, c codecCase) []byte {
	t.Helper()
	var b []byte
	var got protocol.Codec
	switch {
	case c.cursor:
		e := New([]protocol.Codec{c.codec})
		b, got, _ = e.Cursor(nil, c.pix, c.w, c.h)
	case c.quality > 0:
		b, got = New([]protocol.Codec{c.codec}).Lossy(nil, c.pix, c.w, c.h, c.quality)
	default:
		var lossy bool
		b, got, lossy = New([]protocol.Codec{c.codec}).Tile(nil, c.pix, c.w, c.h)
		if lossy {
			t.Fatalf("%s: the tile goes lossy", c.name)
		}
	}
	if got != c.codec {
		t.Fatalf("%s: encoded as %v, want %v", c.name, got, c.codec)
	}
	return b
}

// psnr is the peak signal-to-noise ratio of b against a, over red, green
// and blue, in decibels; +Inf if they are the same.
func psnr(a, b []byte) float64 {
	var sum float64
	n := 0
	for i := 0; i < len(a); i += 4 {
		for k := range 3 {
			d := float64(a[i+k]) - float64(b[i+k])
			sum += d * d
			n++
		}
	}
	if sum == 0 {
		return math.Inf(1)
	}
	return 10 * math.Log10(255*255/(sum/float64(n)))
}

// vector describes c with the payload b, and checks that b decodes.
func vector(t testing.TB, c codecCase, b []byte) codecVector {
	t.Helper()
	v := codecVector{
		Name: c.name, Codec: int(c.codec), Width: c.w, Height: c.h,
		Pixels:  hex.EncodeToString(c.pix),
		Payload: hex.EncodeToString(b),
		Exact:   c.quality == 0,
	}
	if c.codec == deflate {
		var p codec.Palette
		pp := &p
		if !p.Build(c.pix, c.w, c.h) {
			pp = nil
		}
		v.Container = hex.EncodeToString(codec.AppendContainer(nil, c.pix, c.w, c.h, pp))
		var inflated bytes.Buffer
		if _, err := inflated.ReadFrom(flate.NewReader(bytes.NewReader(b))); err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		if got := hex.EncodeToString(inflated.Bytes()); got != v.Container {
			t.Errorf("%s: the payload inflates to %s, want %s", c.name, got, v.Container)
		}
	}
	out, err := decode(c.codec, b, c.w, c.h)
	if err != nil {
		t.Fatalf("%s: %v", c.name, err)
	}
	quality := psnr(c.pix, out.Pix)
	switch {
	case v.Exact && !bytes.Equal(out.Pix, c.pix):
		t.Errorf("%s: the payload decodes to other pixels", c.name)
	case !v.Exact:
		// A margin below Go's decoders, for decoders that convert from
		// YCbCr or invert the DCT another way.
		v.MinPSNR = math.Floor(quality) - 3
		if v.MinPSNR < 20 {
			t.Errorf("%s: PSNR %.1f dB", c.name, quality)
		}
	}
	return v
}

// invalidCodecs are deflate payloads that a decoder refuses.
func invalidCodecs(t testing.TB) []invalidCodec {
	z := func(container []byte) string {
		var out bytes.Buffer
		fw, err := flate.NewWriter(&out, flate.BestSpeed)
		if err != nil {
			t.Fatal(err)
		}
		fw.Write(container)
		fw.Close()
		return hex.EncodeToString(out.Bytes())
	}
	// A valid 3×2 tile of two colours.
	valid := []byte{0, 1, 0xff, 0, 0, 0, 0, 0xff, 0b0100_0000, 0b1000_0000}
	inv := func(name, payload string) invalidCodec {
		return invalidCodec{Name: name, Codec: int(deflate), Width: 3, Height: 2, Payload: payload}
	}
	return []invalidCodec{
		inv("empty payload", ""),
		inv("not DEFLATE", "ffffffff"),
		inv("a truncated stream", z(valid)[:6]),
		inv("a stream without a final block", "000a00f5ff"+hex.EncodeToString(valid)),
		inv("bytes after the stream", z(valid)+"00"),
		inv("an empty container", z(nil)),
		inv("form 4", z(append([]byte{4}, valid[1:]...))),
		inv("a truncated palette", z(valid[:5])),
		inv("one row of indices missing", z(valid[:9])),
		inv("an index beyond the palette", z([]byte{0, 2, 1, 1, 1, 2, 2, 2, 3, 3, 3, 0b1100_0000, 0})),
		inv("an extra row of indices", z(append(bytes.Clone(valid), 0))),
		inv("raw pixels short of the rectangle", z(append([]byte{1}, make([]byte, 3*6-1)...))),
		inv("raw pixels beyond the rectangle", z(append([]byte{1}, make([]byte, 3*6+1)...))),
		inv("a bomb: 1 MiB of zeros", z(make([]byte, 1<<20))),
	}
}

// TestGoldenCodecs checks protocol/testdata/codecs.json: every vector
// decodes as it says, and the file describes the current vectors, except
// that payloads, which a newer compressor or encoder may write
// differently, are only rewritten with -update.
func TestGoldenCodecs(t *testing.T) {
	cases := goldenCases(t)
	fresh := codecGolden{Comment: goldenComment, Invalid: invalidCodecs(t)}
	for _, c := range cases {
		fresh.Vectors = append(fresh.Vectors, vector(t, c, encodeCase(t, c)))
	}
	if *update {
		writeGolden(t, fresh)
	}
	raw, err := os.ReadFile(goldenFile)
	if err != nil {
		t.Fatalf("%v (run go test ./internal/encoder -run TestGoldenCodecs -update)", err)
	}
	var file codecGolden
	if err := json.Unmarshal(raw, &file); err != nil {
		t.Fatal(err)
	}
	// The file's payloads, checked as the current encoder's are.
	kept := fresh
	kept.Vectors = nil
	for i, c := range cases {
		if i >= len(file.Vectors) || file.Vectors[i].Name != c.name {
			t.Fatalf("%s is out of date: vector %d is not %q (run with -update)", goldenFile, i, c.name)
		}
		b, err := hex.DecodeString(file.Vectors[i].Payload)
		if err != nil {
			t.Fatal(err)
		}
		kept.Vectors = append(kept.Vectors, vector(t, c, b))
	}
	want, err := marshalGolden(kept)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(raw, want) {
		t.Errorf("%s is out of date (run go test ./internal/encoder -run TestGoldenCodecs -update)", goldenFile)
	}
}

func marshalGolden(g codecGolden) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(g); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func writeGolden(t *testing.T, g codecGolden) {
	b, err := marshalGolden(g)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(goldenFile, b, 0o644); err != nil {
		t.Fatal(err)
	}
}
