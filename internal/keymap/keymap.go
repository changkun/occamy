// Codes that are not a make code of their own.
const (
	// Pause is Set1's code for the Pause key, whose make code is a
	// sequence: its first two bytes, E1 1D.
	Pause uint16 = 0xe11d
	// PrintScreen is Set1's code for the PrintScreen key.
	PrintScreen uint16 = 0xe037
)

// Set1 returns the set 1 make code of a HID usage: a byte, 0xe0xx for a
// byte after the 0xe0 prefix, Pause for Pause, or 0 for no mapping.
func Set1(usage uint16) uint16 {
	if int(usage) >= len(set1) {
		return 0
	}
	return set1[usage]
}
