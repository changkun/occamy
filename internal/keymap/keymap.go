// Package keymap translates physical keys, the USB HID usages of the
// keyboard page (0x07) in backend.Key.Code, into the make codes of XT
// scan code set 1, which the VNC backend's QEMU Extended Key Events and
// RDP's keyboard events carry. Each backend applies its protocol's
// exceptions on top.
package keymap

// set1 maps usages to set 1 make codes: one byte, or 0xe0 followed by a
